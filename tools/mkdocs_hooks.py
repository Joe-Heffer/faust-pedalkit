"""MkDocs hook: publish the test measurements, schematics and browser demo
alongside the documentation.

The plots (SVG) and the data behind them (CSV) are generated by `make test`
into tests/out/<name>/ and are never committed. This hook adds them to the
site as measurements/<name>/<file>, so an effect page can embed
`../measurements/<name>/freqresp.svg` and link the CSV next to it.

The schematic sheets (SVG) are rendered by `make schematics` from
docs/<name>/schematics/<name>.kicad_sch into build/schematics/<name>/, and
are never committed either. This hook adds them as schematics/<name>/<file>,
so a page can embed `../schematics/<name>/<sheet>.svg`.

The browser demo is built by `make web` into build/web/ and is published as
demo/, so docs/usage/browser.md can link to ../demo/index.html.

Run `make test web schematics` before `make docs`. If an effect has no
measurements yet, or the demo has not been built, the hook logs a warning,
which fails `make docs` (mkdocs build --strict). Schematics are optional, so
a missing one is not a warning; a page that embeds one that was not rendered
fails on its broken link.
"""

import glob
import logging
import os
import re
import sys

from mkdocs.structure.files import File

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import downloads  # noqa: E402

from dspmeta import declares  # noqa: E402

log = logging.getLogger("mkdocs.hooks.measurements")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PUBLISHED = (".svg", ".csv")
WEB = os.path.join(ROOT, "build", "web")
MARKER = re.compile(r"^([ \t]*)<!-- (downloads|download-button):([a-z0-9_]+) -->", re.M)
_latest = {}


def publish(files, config, src_dir, site_dir, suffixes):
    found = sorted(f for f in glob.glob(os.path.join(src_dir, "*")) if f.endswith(suffixes))
    for path in found:
        uri = f"{site_dir}/{os.path.basename(path)}"
        files.append(File.generated(config, uri, abs_src_path=path))
    return found


def on_files(files, config):
    for dsp in sorted(glob.glob(os.path.join(ROOT, "src", "*.dsp"))):
        name = os.path.splitext(os.path.basename(dsp))[0]
        out = os.path.join(ROOT, "tests", "out", name)
        if not publish(files, config, out, f"measurements/{name}", PUBLISHED):
            log.warning("no measurements in tests/out/%s/; run `make test` first", name)
        sch = os.path.join(ROOT, "build", "schematics", name)
        publish(files, config, sch, f"schematics/{name}", (".svg",))

    if not os.path.isfile(os.path.join(WEB, "index.html")):
        log.warning("no browser demo in build/web/; run `make web` first")
        return files
    for path in sorted(glob.glob(os.path.join(WEB, "**", "*"), recursive=True)):
        if os.path.isfile(path):
            uri = "demo/" + os.path.relpath(path, WEB).replace(os.sep, "/")
            files.append(File.generated(config, uri, abs_src_path=path))
    return files


def effects():
    """(name, display name, description) for every effect, from its `declare` lines."""
    out = []
    for dsp in sorted(glob.glob(os.path.join(ROOT, "src", "*.dsp"))):
        name = os.path.splitext(os.path.basename(dsp))[0]
        meta = declares(dsp)
        out.append((name, meta.get("name", name), meta.get("description", "")))
    return out


def on_pre_build(config):
    """Look up the latest published release of each effect once per build."""
    releases = downloads.fetch_releases()
    if releases is None:
        log.info("GitHub is unreachable; download links fall back to the releases page")
    _latest.clear()
    _latest.update(downloads.latest_by_effect(releases))


def on_page_markdown(markdown, page, config, files):
    """Swap the download markers for links (see tools/downloads.py)."""
    names = {name: display for name, display, _ in effects()}
    base = "../" * page.file.src_uri.count("/")

    def links(kind, name):
        if kind == "downloads" and name == "all":
            return downloads.table(effects(), _latest, base)
        if name not in names:
            raise ValueError(f"{page.file.src_uri}: {kind} marker for unknown effect {name!r}")
        if kind == "download-button":
            return downloads.button(name, names[name], _latest.get(name), base)
        return downloads.block(name, names[name], _latest.get(name), base)

    def swap(m):
        # Keep the marker's indent on every line, so it works inside a card or list item.
        indent, kind, name = m[1], m[2], m[3]
        lines = links(kind, name).rstrip("\n").split("\n")
        return "\n".join(indent + line if line else "" for line in lines)

    return MARKER.sub(swap, markdown)
