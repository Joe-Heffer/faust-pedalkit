"""Write plugin_meta.h for the VST3 architecture (tools/vst3/faust-vst3.cpp).

Usage: vst3-meta.py <effect.dsp> <name> <out/plugin_meta.h>

Reads these global declarations from the Faust source:

  declare name     "BassDrive";        -> plug-in name shown by hosts
  declare author   "...";              -> vendor
  declare version  "0.1.0";            -> plug-in version
  declare homepage "https://...";      -> vendor URL (optional)
  declare lv2class "DistortionPlugin"; -> VST3 subcategory (Fx|Distortion, ...)

The class ID is the name-based UUID uuid5(NAMESPACE_DNS, "pedalkit.<name>"),
where <name> is the file name, as in the LV2 URI urn:pedalkit/<name>. Hosts
store it in projects to find the plug-in again, so it must never change for a
released effect: don't rename the .dsp file or alter this derivation.
"""

import sys
import uuid

from dspmeta import declares

# LV2 plugin classes (without prefix) -> VST3 subcategories.
SUBCATEGORY = {
    "DistortionPlugin": "Fx|Distortion",
    "WaveshaperPlugin": "Fx|Distortion",
    "DelayPlugin": "Fx|Delay",
    "ReverbPlugin": "Fx|Reverb",
    "FilterPlugin": "Fx|Filter",
    "EQPlugin": "Fx|EQ",
    "ParaEQPlugin": "Fx|EQ",
    "MultiEQPlugin": "Fx|EQ",
    "DynamicsPlugin": "Fx|Dynamics",
    "CompressorPlugin": "Fx|Dynamics",
    "LimiterPlugin": "Fx|Dynamics",
    "GatePlugin": "Fx|Dynamics",
    "ExpanderPlugin": "Fx|Dynamics",
    "ModulatorPlugin": "Fx|Modulation",
    "ChorusPlugin": "Fx|Modulation",
    "FlangerPlugin": "Fx|Modulation",
    "PhaserPlugin": "Fx|Modulation",
    "PitchPlugin": "Fx|Pitch Shift",
}


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    dsp_path, name, out_path = sys.argv[1:4]
    decl = declares(dsp_path)

    cid = uuid.uuid5(uuid.NAMESPACE_DNS, f"pedalkit.{name}")
    words = [cid.bytes[i : i + 4].hex().upper() for i in range(0, 16, 4)]

    lines = [
        f"// Generated by tools/vst3-meta.py from {dsp_path}. Do not edit.",
        "#pragma once",
        f"#define FX_NAME {c_string(decl.get('name', name))}",
        f"#define FX_VENDOR {c_string(decl.get('author', 'pedalkit'))}",
        f"#define FX_URL {c_string(decl.get('homepage', ''))}",
        f"#define FX_VERSION {c_string(decl.get('version', '0.0.0'))}",
        f"#define FX_SUBCATEGORY {c_string(SUBCATEGORY.get(decl.get('lv2class', ''), 'Fx'))}",
        f'// uuid5(NAMESPACE_DNS, "pedalkit.{name}") = {cid}',
        "#define FX_CID INLINE_UID(" + ", ".join(f"0x{w}" for w in words) + ")",
    ]
    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
