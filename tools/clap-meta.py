"""Write plugin_meta.h for the CLAP architecture (tools/clap/faust-clap.cpp).

Usage: clap-meta.py <effect.dsp> <name> <out/plugin_meta.h>

Reads these global declarations from the Faust source:

  declare name        "BassDrive";        -> plug-in name shown by hosts
  declare description "...";              -> descriptor description
  declare author      "...";              -> vendor
  declare version     "0.1.0";            -> plug-in version
  declare homepage    "https://...";      -> descriptor URL (optional)
  declare lv2class    "DistortionPlugin"; -> CLAP feature (distortion, ...)

The plug-in ID is "pedalkit.<name>", where <name> is the file name, as in the
LV2 URI urn:pedalkit/<name>. Hosts store it in projects to find the plug-in
again, so it must never change for a released effect: don't rename the .dsp
file or alter this derivation.
"""

import sys

from dspmeta import declares

# LV2 plugin classes (without prefix) -> CLAP features (clap/plugin-features.h).
FEATURE = {
    "DistortionPlugin": "distortion",
    "WaveshaperPlugin": "distortion",
    "DelayPlugin": "delay",
    "ReverbPlugin": "reverb",
    "FilterPlugin": "filter",
    "EQPlugin": "equalizer",
    "ParaEQPlugin": "equalizer",
    "MultiEQPlugin": "equalizer",
    "DynamicsPlugin": "compressor",
    "CompressorPlugin": "compressor",
    "LimiterPlugin": "limiter",
    "GatePlugin": "gate",
    "ExpanderPlugin": "expander",
    "ChorusPlugin": "chorus",
    "FlangerPlugin": "flanger",
    "PhaserPlugin": "phaser",
    "PitchPlugin": "pitch-shifter",
}


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    dsp_path, name, out_path = sys.argv[1:4]
    decl = declares(dsp_path)

    # "audio-effect" is the main category; "mono"/"stereo" are added by the
    # architecture, which knows the DSP's channel count.
    features = ["audio-effect"]
    if decl.get("lv2class") in FEATURE:
        features.append(FEATURE[decl["lv2class"]])

    lines = [
        f"// Generated by tools/clap-meta.py from {dsp_path}. Do not edit.",
        "#pragma once",
        f"#define FX_ID {c_string('pedalkit.' + name)}",
        f"#define FX_NAME {c_string(decl.get('name', name))}",
        f"#define FX_DESCRIPTION {c_string(decl.get('description', ''))}",
        f"#define FX_VENDOR {c_string(decl.get('author', 'pedalkit'))}",
        f"#define FX_URL {c_string(decl.get('homepage', ''))}",
        f"#define FX_VERSION {c_string(decl.get('version', '0.0.0'))}",
        "#define FX_FEATURES " + ", ".join(c_string(f) for f in features),
    ]
    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
