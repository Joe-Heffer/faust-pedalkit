"""Generate the project logo into docs/assets/.

The mark is a pedal seen from above with a waveform running through it: a
clean sine goes in on the left and comes out clipped on the right. All colours
and shapes are chosen values; edit them here and rerun.

Writes logo.svg, logo-wordmark.svg, favicon.svg, logo.png (512 px) and
favicon.png (32 px). The wordmark text is converted to outlines with
Shrikhand (SIL OFL 1.1), so no font is needed to view it.
PNGs need `rsvg-convert`.

Usage: tools/logo/build.py
"""

import subprocess
import urllib.request
from pathlib import Path

from matplotlib.font_manager import FontProperties
from matplotlib.path import Path as MplPath
from matplotlib.textpath import TextPath

# Wordmark typeface: Shrikhand by Jonny Pinhorn (SIL OFL 1.1, which allows
# embedding its outlines), chosen for a warm, swashy 1960s amp-badge feel. It
# is fetched from the Google Fonts repository on first use and kept in
# build/; only the outlines are committed.
FONT_URL = "https://raw.githubusercontent.com/google/fonts/main/ofl/shrikhand/Shrikhand-Regular.ttf"
FONT = Path(__file__).resolve().parents[2] / "build" / "logo" / "Shrikhand-Regular.ttf"

OUT = Path(__file__).resolve().parents[2] / "docs" / "assets"

# Chosen colours: slate tile, off-white pedal outline, amber signal.
SLATE = "#1f2933"
BODY = "#2b3a47"
LIGHT = "#e8edf1"
AMBER = "#f5a524"

# REUSE-IgnoreStart
HEADER = (
    "<!--\n"
    "SPDX-FileCopyrightText: 2026 Joe Heffer\n"
    "SPDX-License-Identifier: CC-BY-4.0\n"
    "Generated by tools/logo/build.py; edit that, not this file.\n"
    "-->\n"
)
# REUSE-IgnoreEnd

# Waveform through the pedal: one period of sine (left), the same period
# clipped with soft shoulders (right). Zero crossings every 34 units.
SINE = "M20,128 C31,84 43,84 54,128 S77,172 88,128"
CLIPPED = (
    "M168,128 C171,100 173,96 180,96 H190 C197,96 199,100 202,128 "
    "C205,156 207,160 214,160 H224 C231,160 233,156 236,128"
)


def wave(width):
    return (
        f'<g fill="none" stroke="{AMBER}" stroke-width="{width}" '
        'stroke-linecap="round" stroke-linejoin="round">'
        f'<path d="{SINE}"/><path d="{CLIPPED}"/></g>'
    )


def mark():
    return (
        f'<rect width="256" height="256" rx="48" fill="{SLATE}"/>'
        + wave(9)
        + f'<rect x="88" y="32" width="80" height="192" rx="16" fill="{BODY}" '
        f'stroke="{LIGHT}" stroke-width="6"/>'
        f'<circle cx="128" cy="68" r="13" fill="none" stroke="{LIGHT}" stroke-width="5"/>'
        f'<path d="M128,68 V58" stroke="{AMBER}" stroke-width="5" stroke-linecap="round"/>'
        f'<circle cx="128" cy="104" r="6" fill="{AMBER}"/>'
        f'<circle cx="128" cy="180" r="24" fill="none" stroke="{LIGHT}" stroke-width="6"/>'
        f'<circle cx="128" cy="180" r="12" fill="{LIGHT}"/>'
    )


def favicon():
    # Fewer, heavier details so it survives at 16-32 px.
    return (
        f'<rect width="256" height="256" rx="48" fill="{SLATE}"/>'
        + wave(16)
        + f'<rect x="84" y="28" width="88" height="200" rx="20" fill="{BODY}" '
        f'stroke="{LIGHT}" stroke-width="12"/>'
        f'<circle cx="128" cy="86" r="11" fill="{AMBER}"/>'
        f'<circle cx="128" cy="170" r="28" fill="{LIGHT}"/>'
    )


def svg(body, w, h, title):
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" '
        f'width="{w}" height="{h}" role="img" aria-label="{title}">\n'
        f"{HEADER}<title>{title}</title>\n{body}\n</svg>\n"
    )


def text_path(text, size, x, y):
    """Outline `text` as one SVG path with its baseline at (x, y)."""
    if not FONT.exists():
        FONT.parent.mkdir(parents=True, exist_ok=True)
        urllib.request.urlretrieve(FONT_URL, FONT)
    tp = TextPath((0, 0), text, size=size, prop=FontProperties(fname=str(FONT)))
    d = []
    for verts, code in tp.iter_segments():
        pts = (
            []
            if code == MplPath.CLOSEPOLY
            else [
                f"{x + vx:.2f},{y - vy:.2f}"
                for vx, vy in zip(verts[0::2], verts[1::2], strict=True)
            ]
        )
        d.append(
            {
                MplPath.MOVETO: "M",
                MplPath.LINETO: "L",
                MplPath.CURVE3: "Q",
                MplPath.CURVE4: "C",
                MplPath.CLOSEPOLY: "Z",
            }[code]
            + " ".join(pts)
        )
    path = f'<path d="{" ".join(d)}" class="t" fill-rule="nonzero"/>'
    return path, tp.get_extents().x1


def wordmark():
    # Mark at 256 units, text to its right. The text class switches
    # light or dark text by colour scheme; the tile keeps its own colours.
    words, width = text_path("Pedal Kit", 100, 288, 150)
    return svg(
        f"<style>.t{{fill:{SLATE}}}@media(prefers-color-scheme:dark){{.t{{fill:{LIGHT}}}}}</style>"
        f"{mark()}{words}",
        round(288 + width + 24),
        256,
        "Pedal Kit",
    )


def render(src, dst, px):
    subprocess.run(
        ["rsvg-convert", "-w", str(px), "-h", str(px), "-o", str(dst), str(src)], check=True
    )


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "logo.svg").write_text(svg(mark(), 256, 256, "Pedal Kit logo"))
    (OUT / "favicon.svg").write_text(svg(favicon(), 256, 256, "Pedal Kit"))
    (OUT / "logo-wordmark.svg").write_text(wordmark())
    render(OUT / "logo.svg", OUT / "logo.png", 512)
    render(OUT / "favicon.svg", OUT / "favicon.png", 32)


if __name__ == "__main__":
    main()
